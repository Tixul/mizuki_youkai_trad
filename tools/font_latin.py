# --- table caractère -> code ---
CODE = {}
for i, c in enumerate('abcdefghijklmnopqrstuvwxyz'):
    CODE[c] = 0x00 + i
for i, c in enumerate('éèêëàâùûîïôçœ'):
    CODE[c] = 0x1A + i
for i, c in enumerate("':;…()"):
    CODE[c] = 0x27 + i
for i, c in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
    CODE[c] = 0x40 + i
CODE.update({'Ç': 0x5A, 'É': 0x2D, ',': 0x37, '.': 0x38, ' ': 0x3A, '«': 0x3B, '»': 0x3C,
             '-': 0x3F, '?': 0x77, '!': 0x78})
DIGITS = {str(i): 0xA0 + i for i in range(10)}   # glyphes d'origine conservés
assert len(set(CODE.values())) == len(CODE)
assert all(c < 0xF0 for c in CODE.values())


def tile_2bpp(rows, ink=3, bg=1, x0=1):
    """8 lignes de 5 pixels -> tuile K2GE 2bpp (16 octets, pixel 0 = bits 15-14)."""
    out = bytearray()
    for r in rows:
        w = 0
        for x in range(8):
            gx = x - x0
            on = 0 <= gx < 5 and r[gx] == '#'
            w |= (ink if on else bg) << (14 - 2 * x)
        out += bytes((w & 0xFF, w >> 8))
    return bytes(out)


def width(ch):
    """Largeur réelle (pour le texte proportionnel des menus en image)."""
    rows = G[ch]
    cols = [x for x in range(5) if any(r[x] == '#' for r in rows)]
    return (min(cols), max(cols) + 1) if cols else (0, 2)


def add_glyphs(extra):
    """Ajoute les lettres d'une langue : {'ñ': (0x2D, [8 lignes de 5 car.]), ...}."""
    forbidden = set(range(0xF0, 0x100)) | set(range(0xA0, 0xAA)) | {0x3A, 0x79, 0x7A, 0x7D, 0x7E}
    for ch, (code, rows) in extra.items():
        rows = list(rows) + ['.....'] * (8 - len(rows))
        if code in forbidden:
            raise SystemExit(f'glyphe {ch!r} : code {code:#04x} réservé')
        if not (len(rows) == 8 and all(len(r) == 5 for r in rows)):
            raise SystemExit(f'glyphe {ch!r} : il faut 8 lignes de 5 caractères')
        if code in CODE.values() and CODE.get(ch) != code:
            owner = [c for c, v in CODE.items() if v == code][0]
            raise SystemExit(f'glyphe {ch!r} : code {code:#04x} déjà pris par {owner!r}')
        G[ch] = rows
        CODE[ch] = code
